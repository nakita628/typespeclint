// Writes examples/config/typespeclint.config.full.ts: every rule with every option, set to its default.

import { CATEGORIES, ruleSpecs } from '../dist/index.js'
import { emit, finish } from './emit.mjs'

const file = new URL('../../../examples/config/typespeclint.config.full.ts', import.meta.url)

const isPlain = (v) => v !== null && typeof v === 'object' && !Array.isArray(v)
const key = (k) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k))

function format(value, indent, unset = {}) {
  const pad = ' '.repeat(indent)
  if (Array.isArray(value)) {
    if (value.every((v) => !isPlain(v))) {
      const items = value.map((v) => JSON.stringify(v))
      const inline = `[${items.join(', ')}]`
      if (inline.length + indent <= 90) return inline
      // Fill lines with as many items as fit.
      const lines = []
      for (const item of items) {
        const last = lines.at(-1)
        if (last !== undefined && last.length + item.length + indent + 4 <= 90)
          lines[lines.length - 1] = `${last} ${item},`
        else lines.push(`${item},`)
      }
      return `[\n${lines.map((l) => `${pad}  ${l}`).join('\n')}\n${pad}]`
    }
    return `[\n${value.map((v) => `${pad}  ${format(v, indent + 2)},`).join('\n')}\n${pad}]`
  }
  if (isPlain(value)) {
    const entries = Object.entries(value).map(([k, v]) => `${key(k)}: ${format(v, indent + 2)}`)
    // Options without a default are listed commented out, with an example value.
    const extra = Object.entries(unset).map(
      ([k, v]) =>
        `// ${key(k)}: ${format(v, indent + 2).replaceAll('"', "'")}, (not set by default)`,
    )
    const inline = `{ ${entries.join(', ')} }`
    if (extra.length === 0 && !inline.includes('\n') && inline.length + indent <= 90)
      return entries.length ? inline : '{}'
    return `{\n${[...entries.map((e) => `${e},`), ...extra].map((e) => `${pad}  ${e}`).join('\n')}\n${pad}}`
  }
  return JSON.stringify(value)
}

const sections = Object.entries(CATEGORIES).map(([category, title]) => {
  const rules = ruleSpecs
    .filter((spec) => spec.category === category)
    .map((spec) => {
      const hasOptions = Object.keys(spec.defaults).length > 0 || spec.unset
      const value = hasOptions ? `["warn", ${format(spec.defaults, 4, spec.unset)}]` : `"warn"`
      const state = spec.recommended ? 'In `recommended`.' : 'Not in `recommended` (opt-in).'
      return `    // ${spec.description} ${state}\n    "${spec.name}": ${value},`
    })
  return `    // --- ${title} (category: ${category}) ---\n\n${rules.join('\n\n')}`
})

const source = `// Every typespeclint rule with every option, set to its default value.
// Generated by \`pnpm readme\` in packages/tsplint; copy it and edit what your guidelines change.
//
//   '<rule>': 'off'                  the rule does not run
//   '<rule>': 'warn'                 the rule reports warnings, with its default options
//   '<rule>': 'error'                the rule fails the compilation
//   '<rule>': ['warn', { ... }]      severity and options (merged over the defaults)
//
// A reference, not a config in use: typespeclint loads \`typespeclint.config.ts\`, not this file.
// Every rule is listed as 'warn' here, so used as a config it runs all ${ruleSpecs.length} rules.

import { defineConfig } from "typespeclint";

export default defineConfig({
  // Presets to start from: 'recommended' (the default) or 'all'.
  extends: ["recommended"],

  // Severity of a whole checklist section, applied after the presets and before \`rules\`.
  categories: {
${Object.entries(CATEGORIES)
  .map(([id, title]) => `    // ${id}: 'error', // ${title}`)
  .join('\n')}
  },

  rules: {
${sections.join('\n\n')}
  },
});
`

finish(
  emit(file, source) ? [] : ['examples/config/typespeclint.config.full.ts'],
  'The full config is',
)
